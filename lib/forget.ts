/**
 * «Забудь» в чате — детерминированный сценарий без модели (как стоп-слова и
 * часы). Память никогда не удаляется: явная просьба забыть открывает новую
 * эпоху (sql/0005_memory_reset.sql) — бот честно начинает с чистого листа,
 * архив остаётся у владельца для профиля и стратегий.
 *
 * Тематические просьбы («забудь про Баку», «забудь про историю с доставкой»)
 * сюда не попадают — их ведёт модель по промпт-правилам: «сам не возвращаюсь
 * к теме, пересказ по прямой просьбе работает».
 *
 * Внимание: в JS \b/\w работают только с ASCII — границы слов для кириллицы
 * задаются явными lookaround-классами [а-яё] (см. STOP_WORD_PATTERNS в nudge.ts).
 */

/** Явная просьба забыть всё / стереть переписку / удалить данные. */
const FORGET_PATTERNS: RegExp[] = [
  // «забудь всё / обо мне / эту историю / этот разговор / мои данные»
  /(?<!не\s)(?<![а-яёa-z])(забудь|забудьте|забыть|сотри|сотрите|стереть|удали|удалите)(?![а-яёa-z])[^.!?\n]{0,24}(?<![а-яёa-z])(всё|все|обо\s+мне|про\s+меня|меня|нас|эту\s+историю|этот\s+разговор|наши\s+данные|мои\s+данные)(?![а-яё])/i,
  // «забудь наш разговор / мою переписку / всю историю / данные»
  // («про …» — тема, не полный сброс: "забудь про историю с доставкой")
  /(?<!не\s)(?<![а-яёa-z])(забудь|забудьте|забыть|сотри|сотрите|стереть|удали|удалите)(?![а-яёa-z])[^.!?\n]{0,24}(?<![а-яёa-z])(?<!про\s)(разговор|переписк[а-яё]*|истори[а-яё]*|диалог[а-яё]*|данные)(?![а-яё])/i,
];

/** True when the visitor explicitly asks to forget everything. */
export function isForgetRequest(text: string): boolean {
  return FORGET_PATTERNS.some((pattern) => pattern.test(text));
}

/**
 * Канонический ответ: правда (активная память пуста), без заявлений об
 * «удалении» — архив существует, и бот не врёт о своих действиях.
 */
export const FORGET_REPLY =
  'Хорошо, я тебя больше не знаю — ни тебя, ни нашего разговора. Начнём с чистого листа: чем могу помочь?';
