export const KNOWLEDGE_PACK_IDS = new Set(KNOWLEDGE_PACKS.map((pack) => pack.id));

/** Выбранные наборы в порядке каталога (неизвестные id отброшены). */
export function selectedKnowledgePacks(ids: unknown): KnowledgePack[] {
  if (!Array.isArray(ids)) return [];
  const wanted = new Set(ids.filter((id): id is string => typeof id === 'string'));
  return KNOWLEDGE_PACKS.filter((pack) => wanted.has(pack.id));
}

